type Entry = { name: string; section: Section };

/** 表記ゆれを比較するためのキー（全角半角・カタカナ/ひらがな・空白の違いを吸収） */
export function ingredientKey(raw: string): string {
  return raw
    .normalize('NFKC')
    .replace(/\s+/g, '')
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .toLowerCase();
}

const index = new Map<string, Entry>();
const canonical = new Map<string, Entry>();

for (const [section, list] of Object.entries(DICTIONARY) as [Section, string][]) {
  for (const raw of list.split(/,(?![^(]*\))/)) {
    const m = raw.trim().match(/^([^(]+)(?:\((.*)\))?$/);
    if (!m) continue;
    const name = m[1]!.trim();
    const entry = { name, section };
    canonical.set(name, entry);
    for (const alias of [name, ...(m[2]?.split(',') ?? [])]) {
      const key = ingredientKey(alias);
      if (!index.has(key)) index.set(key, entry);
    }
  }
}

/** 材料名を正式名にそろえる（辞書にないものは空白・全角を整えただけで返す） */
export function normalizeIngredientName(raw: string): string {
  return index.get(ingredientKey(raw))?.name ?? raw.normalize('NFKC').trim();
}

/** 材料の区分（辞書にない場合は undefined） */
export function sectionOf(name: string): Section | undefined {
  return index.get(ingredientKey(name))?.section;
}

export function isKnownIngredient(name: string): boolean {
  return canonical.has(name);
}

/** 入力補完用の正式名一覧 */
export const INGREDIENT_NAMES: readonly string[] = [...canonical.keys()];
