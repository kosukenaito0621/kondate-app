/** まだ読んでいないお知らせの数（seenId は最後に見たときの先頭の id） */
export function unreadNewsCount(seenId: string | null): number {
  if (!seenId) return NEWS.length;
  const i = NEWS.findIndex((n) => n.id === seenId);
  return i < 0 ? NEWS.length : i;
}
